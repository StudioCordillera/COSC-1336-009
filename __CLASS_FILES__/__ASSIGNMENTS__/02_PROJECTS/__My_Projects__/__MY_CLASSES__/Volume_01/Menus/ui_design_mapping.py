"""
═══════════════════════════════════════════════════════════════════════════════
                            DESIGN PALETTE REFERENCE
═══════════════════════════════════════════════════════════════════════════════

MAPPING SUMMARY:

1. MAIN MENU
   - Wrapper: Double-line box (╔═══╗) for prominence
   - Title: Centered header with double-line separator
   - Choices: Single-line box (┌───┐) with numbered list
   - Prompt: Simple text with input field

2. REGISTRATION FORM
   - Wrapper: Plus-style box (+===+) for forms
   - Fields: Labeled inputs with brackets |____|
   - Buttons: Inline buttons at bottom

3. COLLECTION VIEW
   - Header: Double-line box with page info
   - Filters: Collapsible panel with single-line box
   - Table: Grid with plus-corners (+---+)
   - Actions: Dropdown menu or button group

4. SETTINGS
   - Menu: Single-line box with options list
   - Panels: Nested boxes for different settings
   - Preview: Highlighted area showing changes

5. DIALOGS & CONFIRMATIONS
   - Warning: Bold header with warning symbol
   - Content: Indented list or description
   - Actions: Button row at bottom

LINE STYLES USAGE:
- ═══ : Major headers and titles
- ─── : Section dividers and boxes
- ___ : Input field underlines
- ━━━ : Strong emphasis or loading
- +++ : Box corners and table grids
- ┌┐└┘: Rounded/soft box corners
- ╔╗╚╝: Formal/prominent box corners
"""
