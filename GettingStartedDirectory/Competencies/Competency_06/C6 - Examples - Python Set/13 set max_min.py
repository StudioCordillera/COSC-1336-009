# set - max/min
# using max(arg1, arg2, *args); min(arg1, arg2, *args)
print('Maximum is:', max(1, 3, 2, 5, 4))
print('Minimum is:', min(1, 3, 2, 5, 4))

# using max(iterable); min(iterable)
num = [1, 3, 2, 8, 5, 10, 6]
print('Maximum is:', max(num))
print('Minimum is:', min(num))
